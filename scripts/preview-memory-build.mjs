import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, copyFileSync, writeFileSync, rmSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { execFileSync } from 'node:child_process';

const PROJECT = 'diamond-geolabel';
const APP_ID = 'geolabel';
const APP_NAME = 'GeoLabel';
const EXPECTED_CONFIG_SHA256 = 'db97ceb71b1f148aa56ec928830f2ad06fba247971804f4748d695c12c1db75b';
const OUTPUT_CONFIG = 'dist/memory/memory-config.js';
const isPreview = process.env.VERCEL_ENV === 'preview';
const host = process.env.VERCEL_URL || '';
const hostPattern = new RegExp(`^${PROJECT}(?:-[a-z0-9-]+)?\\.vercel\\.app$`);
function stable(value) {
  if (Array.isArray(value)) return `[${value.map(stable).join(',')}]`;
  if (value && typeof value === 'object') return `{${Object.keys(value).sort().map(k => JSON.stringify(k)+':'+stable(value[k])).join(',')}}`;
  return JSON.stringify(value);
}
function writeConfig(firebaseConfig = null, allowedHost = null) {
  const out = `// Generated by the preview-only build. Source config remains null.
`+
`window.PROJECT_MEMORY_CONFIG = (() => {
`+
`  const firebaseConfig = ${JSON.stringify(firebaseConfig)};
`+
`  const allowedHost = ${JSON.stringify(allowedHost)};
`+
`  const enabled = allowedHost !== null && location.hostname === allowedHost;
`+
`  return { appId: ${JSON.stringify(APP_ID)}, appName: ${JSON.stringify(APP_NAME)}, expectedProjectId: ${JSON.stringify(PROJECT)}, firebaseConfig: enabled ? firebaseConfig : null };
`+
`})();
`;
  const target = join(process.cwd(), OUTPUT_CONFIG); mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, out);
}
if (!isPreview) { writeConfig(); }
else {
  if (!hostPattern.test(host)) throw new Error(`Preview build refused: VERCEL_URL must be an exact ${PROJECT}.vercel.app deployment host`);
  if (!process.env.PROJECT_MEMORY_FIREBASE_CONFIG) throw new Error('Preview build refused: PROJECT_MEMORY_FIREBASE_CONFIG is required');
  let config; try { config = JSON.parse(process.env.PROJECT_MEMORY_FIREBASE_CONFIG); } catch { throw new Error('Preview build refused: PROJECT_MEMORY_FIREBASE_CONFIG must be valid JSON'); }
  const hash = createHash('sha256').update(stable(config)).digest('hex');
  if (hash !== EXPECTED_CONFIG_SHA256 || config.projectId !== PROJECT) throw new Error('Preview build refused: public Firebase config does not match the approved app config');
  writeConfig(config, host);
}
execFileSync('npm', ['exec', '--', 'vite', 'build'], {stdio:'inherit'});
// Vite copies public/ into dist/, so inject after the actual frontend build.
if (isPreview) writeConfig(JSON.parse(process.env.PROJECT_MEMORY_FIREBASE_CONFIG), host);
else writeConfig();
